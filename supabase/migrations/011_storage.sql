insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('property-documents','property-documents',false,20971520,array['application/pdf','image/jpeg','image/png'])
on conflict(id) do update set public=false,file_size_limit=excluded.file_size_limit,allowed_mime_types=excluded.allowed_mime_types;

create policy storage_reserved_insert on storage.objects for insert to authenticated with check(
 bucket_id='property-documents' and exists(
  select 1 from public.document_versions dv
  where dv.storage_bucket=bucket_id and dv.storage_path=name and dv.upload_status='RESERVED'
  and dv.reserved_by_user_id=(select auth.uid())
 )
);
